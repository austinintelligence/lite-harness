import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { currentCommit, currentTree, evaluateReleaseTruth, isExternalOnlyDefect, isExternalOnlyRequirement } from "./release-truth-lib.mjs";

const requiredTestCommands = [
  "test:unit", "test:contracts", "test:migrations", "test:ipc", "test:sdk", "test:docker", "test:recovery",
  "test:providers", "test:plugins", "test:skills", "test:mcp", "test:browser", "test:integrations", "test:automation",
  "test:subagents", "test:security", "test:chaos", "test:install", "test:performance", "test:release",
];
const root = resolve(import.meta.dirname, "..");
const requirements = JSON.parse(readFileSync(resolve(root, "docs", "requirements", "alpha-ledger.yaml"), "utf8")).requirements;
const defects = JSON.parse(readFileSync(resolve(root, "docs", "requirements", "defect-ledger.yaml"), "utf8")).defects;
const packageJson = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
const head = currentCommit(root);
const tree = currentTree(root, head);
const output = resolve(root, "BLOCKERS.md");
const rendered = render();

if (process.argv.includes("--check")) {
  const current = readFileSync(output, "utf8").replaceAll("\r\n", "\n");
  if (current !== rendered) {
    process.stderr.write("BLOCKERS.md is stale; run pnpm generate:blockers.\n");
    process.exitCode = 1;
  } else {
    process.stdout.write("Generated blocker report is current.\n");
  }
} else {
  writeFileSync(output, rendered);
  process.stdout.write("Generated BLOCKERS.md from release truth and the mission's external gates.\n");
}

function render() {
  const { requirementEvaluations, defectEvaluations } = evaluateReleaseTruth({ requirements, defects }, { root, head, tree });
  const alphaRequirements = requirements.filter((row) => row.required === true);
  const blocked = requirementEvaluations.filter((item) => item.row.required === true && !item.verified && !isExternalOnlyRequirement(item.row));
  const externalRequirements = requirementEvaluations.filter((item) => item.row.required === true && isExternalOnlyRequirement(item.row));
  const open = defectEvaluations.filter((item) => !item.closed && !isExternalOnlyDefect(item.defect)).map((item) => item.defect);
  const externalDefects = defectEvaluations.filter((item) => isExternalOnlyDefect(item.defect)).map((item) => item.defect);
  const severity = countBy(open, "severity");
  const missingCommands = requiredTestCommands.filter((name) => !packageJson.scripts?.[name]);
  const localQualified = blocked.length === 0 && open.length === 0 && missingCommands.length === 0;
  const verdict = localQualified ? "VERIFIED_WINDOWS_LOCAL_ALPHA" : "NOT YET A VERIFIED ALPHA";
  const lines = [
    "# Lite-Harness release blockers", "",
    "> Generated by `pnpm generate:blockers`. This file is intentionally release-blocking; do not turn missing evidence into a skip or substitute.", "",
    "## Current verdict", "",
    `**${verdict}.** ${localQualified ? "Windows 11 x64 + WSL2 + Docker Desktop is the verified product environment; all Windows-local release truth is complete. Cross-platform and direct-provider lanes remain NOT_QUALIFIED_EXTERNAL and are non-blocking for this tier." : "Local implementation and verification work remains, so no external input is the sole blocker yet."}`, "",
    `- Alpha-required rows without verified status: ${blocked.length} of ${alphaRequirements.length}`,
    `- Future external rows not included in the Windows-local verdict: ${externalRequirements.length}`,
    `- Non-alpha rows retained in ledger: ${requirements.length - alphaRequirements.length}`,
    `- Open or unproven critical defects: ${severity.critical ?? 0}`,
    `- Open or unproven high defects: ${severity.high ?? 0}`,
    `- Critical/high defects retained for future external qualification: ${externalDefects.length}`,
    `- Missing required test command surfaces: ${missingCommands.length}`,
    "", "## Highest-priority local blockers", "",
    "| Defect or gate | Required local work |", "| --- | --- |",
    ...(localQualified
      ? ["| None | All locally actionable requirements and critical/high defects have current zero-skip evidence. |"]
      : [
          "| Evidence truth / M0 | Use one versioned evidence envelope, prove requirement-ID coverage, collect same-candidate evidence in CI, and keep generated status evidence-aware. |",
          "| Current local regression evidence | Re-run every required zero-skip producer on one clean committed tree and bind each requirement and defect to the exact evidence envelope. |",
          "| BD-063 | Keep architecture and generated status explicitly evidence-qualified; current evidence must control every verified claim. |",
        ]),
    "", "## Required test commands not yet present", "",
    ...(missingCommands.length ? missingCommands.map((name) => `- \`${name}\``) : ["- None."]),
    "", "## Future external qualification (non-blocking for Windows local alpha)", "",
    "| Input | Blocks | Completion evidence |", "| --- | --- | --- |",
    "| Real supported hosts/runners: Linux rootful/rootless (and arm64 if advertised), macOS Docker Desktop, Windows 11 Docker Desktop/WSL2 | A01, BD-058, M9-M11 | Same package hashes and OCI digest complete the required host/restart/sleep/offline matrix with matching fixture tree hashes. |",
    "| Operator-provided direct OpenAI, direct Anthropic, and delegated Codex accounts | A16-A17, M5, M11 | Redacted live conformance evidence produced by the shared provider kit. |",
    "| Owner-approved collision-checked product, npm, PyPI, GitHub/container, domain, and trademark identity | P00, BD-064, publication | Accepted ADR 0033 and matching package/registry configuration. |",
    "| Signing authority and registry promotion access | M11 publication | SBOM, provenance, signatures, and promotion of the exact tested hashes/digests. |",
    "", "These inputs remain future qualification lanes and are recorded without blocking VERIFIED_WINDOWS_LOCAL_ALPHA. Do not use them to qualify the Windows-local product tier or substitute them for Hermes-backed local evidence.",
  ];
  return `${lines.join("\n")}\n`;
}

function countBy(rows, field) {
  return rows.reduce((counts, row) => ({ ...counts, [row[field]]: (counts[row[field]] ?? 0) + 1 }), {});
}
